import React from 'react';
import { Card } from '@/components/ui/Card';
import { Badge } from '@/components/ui/Badge';
import { ConfidenceBar } from '@/components/ui/ConfidenceBar';
import { OutletChips } from './OutletChips';
import { formatDate } from '@/lib/format';

interface StoryCardProps {
  storyId: string;
  title?: string | null;
  outletsCovering: string[];
  numArticles: number;
  synthesizedTruth: string;
  confidence?: number;
  createdAt?: string | null;
  hasContradictions?: boolean;
}

function coverageBadge(numOutlets: number, hasContradictions?: boolean) {
  if (hasContradictions)
    return <Badge tone="warn">⚠ CONFLICTING COVERAGE</Badge>;
  if (numOutlets >= 4) return <Badge tone="accent">STRONG CONSENSUS</Badge>;
  if (numOutlets >= 2) return <Badge tone="accent">MULTI-OUTLET</Badge>;
  return <Badge tone="gray">LIMITED COVERAGE</Badge>;
}

export const StoryCard = React.memo(function StoryCard({
  storyId,
  title,
  outletsCovering,
  numArticles,
  synthesizedTruth,
  confidence,
  createdAt,
  hasContradictions,
}: StoryCardProps) {
  return (
    <Card className="mb-6">
      {/* Meta row */}
      <div className="flex flex-wrap items-center gap-2.5 mb-3">
        {coverageBadge(outletsCovering.length, hasContradictions)}
        <span className="text-xs text-ink-muted">
          {outletsCovering.length} outlet
          {outletsCovering.length === 1 ? '' : 's'} · {numArticles} article
          {numArticles === 1 ? '' : 's'}
          {createdAt && <> · Ingested {formatDate(createdAt)}</>}
        </span>
      </div>

      {/* Title */}
      <h1 className="font-display text-3xl font-bold leading-tight tracking-tight break-words mb-3">
        {title || storyId}
      </h1>

      <div className="mb-5">
        <OutletChips outlets={outletsCovering} />
      </div>

      {/* Synthesis */}
      <div className="bg-accent-wash border-l-4 border-accent rounded-xl px-5 py-4">
        <p className="text-xs font-bold uppercase tracking-wider text-accent-deep mb-1.5">
          Source of truth synthesis
        </p>
        <p className="text-[15px] leading-relaxed">{synthesizedTruth}</p>

        {typeof confidence === 'number' && (
          <div className="flex flex-wrap items-center gap-3 mt-3.5 pt-3 border-t border-accent-edge">
            <span className="text-xs text-ink-muted">Confidence</span>
            <ConfidenceBar value={confidence} />
            <span className="text-[11px] text-ink-muted">
              Generated by Gemini · workspace.trust_dev.story_records
            </span>
          </div>
        )}
      </div>
    </Card>
  );
});
