import React from 'react';
import { Card } from '@/components/ui/Card';
import { ConfidenceBar } from '@/components/ui/ConfidenceBar';
import { OutletChips } from './OutletChips';
import { formatDate } from '@/lib/format';

interface StoryCardProps {
  storyId: string;
  title?: string | null;
  outletsCovering: string[];
  numArticles: number;
  synthesizedTruth: string;
  confidence?: number;
  createdAt?: string | null;
}

const getStatusLabel = (numOutlets: number) => {
  if (numOutlets >= 4) return '✅ STRONG CONSENSUS';
  if (numOutlets >= 3) return '⚠️ CONFLICTING INFO';
  return '❓ LIMITED COVERAGE';
};

export const StoryCard = React.memo(function StoryCard({
  storyId,
  title,
  outletsCovering,
  numArticles,
  synthesizedTruth,
  confidence,
  createdAt,
}: StoryCardProps) {
  return (
    <Card className="shadow-lg mb-6">
      {/* Header */}
      <div className="flex justify-between items-start mb-4 gap-4">
        <div className="min-w-0">
          <h2 className="text-2xl font-bold break-all">
            {title || `Story: ${storyId}`}
          </h2>
          <p className="text-gray-600">
            Reported by {outletsCovering.length} outlet
            {outletsCovering.length === 1 ? '' : 's'} | {numArticles} article
            {numArticles === 1 ? '' : 's'}
            {createdAt && <> | Ingested {formatDate(createdAt)}</>}
          </p>
        </div>
        <span className="text-lg font-bold whitespace-nowrap">
          {getStatusLabel(outletsCovering.length)}
        </span>
      </div>

      {/* Outlets */}
      <div className="mb-6 p-4 bg-blue-50 rounded-lg">
        <h3 className="font-bold mb-3">📰 OUTLETS COVERING THIS STORY</h3>
        <OutletChips outlets={outletsCovering} />
      </div>

      {/* Synthesis */}
      <div className="p-4 bg-green-50 rounded-lg border-l-4 border-green-500">
        <h3 className="font-bold mb-2">🔍 SOURCE OF TRUTH SYNTHESIS</h3>
        <p className="text-gray-800 leading-relaxed">{synthesizedTruth}</p>

        {typeof confidence === 'number' && (
          <div className="mt-4 pt-4 border-t border-green-200 flex items-center justify-between">
            <span className="text-sm text-gray-600">Confidence Level:</span>
            <ConfidenceBar value={confidence} />
          </div>
        )}

        <p className="text-xs text-gray-600 mt-4">
          Generated by Gemini Agent | workspace.trust_dev.story_records
        </p>
      </div>
    </Card>
  );
});
