import React from 'react';

interface StoryCardProps {
  storyId: string;
  outletsCovering: string[];
  numArticles: number;
  synthesizedTruth: string;
  confidence?: number;
}

export const StoryCard: React.FC<StoryCardProps> = ({
  storyId,
  outletsCovering,
  numArticles,
  synthesizedTruth,
  confidence,
}) => {
  const getStatusIcon = (numOutlets: number) => {
    if (numOutlets >= 4) return '✅ STRONG CONSENSUS';
    if (numOutlets >= 3) return '⚠️ CONFLICTING INFO';
    return '❓ LIMITED COVERAGE';
  };

  return (
    <div className="bg-white rounded-lg shadow-lg p-6 mb-6">
      {/* Header */}
      <div className="flex justify-between items-start mb-4">
        <div>
          <h2 className="text-2xl font-bold">Story: {storyId}</h2>
          <p className="text-gray-600">
            Reported by {outletsCovering.length} outlets | {numArticles} articles
          </p>
        </div>
        <span className="text-lg font-bold">{getStatusIcon(outletsCovering.length)}</span>
      </div>

      {/* Outlets */}
      <div className="mb-6 p-4 bg-blue-50 rounded-lg">
        <h3 className="font-bold mb-3">📰 OUTLETS COVERING THIS STORY</h3>
        <div className="flex flex-wrap gap-2">
          {outletsCovering.map((outlet) => (
            <span
              key={outlet}
              className="px-3 py-1 bg-blue-200 text-blue-900 rounded-full text-sm font-medium"
            >
              {outlet}
            </span>
          ))}
        </div>
      </div>

      {/* Synthesis */}
      <div className="p-4 bg-green-50 rounded-lg border-l-4 border-green-500">
        <h3 className="font-bold mb-2">🔍 SOURCE OF TRUTH SYNTHESIS</h3>
        <p className="text-gray-800 leading-relaxed">{synthesizedTruth}</p>

        {confidence && (
          <div className="mt-4 pt-4 border-t border-green-200">
            <div className="flex items-center justify-between">
              <span className="text-sm text-gray-600">Confidence Level:</span>
              <div className="flex items-center gap-2">
                <div className="w-32 h-2 bg-gray-300 rounded-full overflow-hidden">
                  <div
                    className="h-full bg-green-500"
                    style={{ width: `${confidence * 100}%` }}
                  />
                </div>
                <span className="text-sm font-bold">{(confidence * 100).toFixed(0)}%</span>
              </div>
            </div>
          </div>
        )}

        <p className="text-xs text-gray-600 mt-4">
          Generated by Gemini Agent | workspace.trust_dev.story_records
        </p>
      </div>

      {/* Actions */}
      <div className="flex gap-2 mt-6">
        <button className="px-4 py-2 bg-blue-600 text-white rounded-lg hover:bg-blue-700 text-sm">
          View Full Analysis
        </button>
        <button className="px-4 py-2 bg-gray-200 text-gray-800 rounded-lg hover:bg-gray-300 text-sm">
          Export Report
        </button>
        <button className="px-4 py-2 bg-gray-200 text-gray-800 rounded-lg hover:bg-gray-300 text-sm">
          Share
        </button>
      </div>
    </div>
  );
};
